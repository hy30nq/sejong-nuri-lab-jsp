    public static int execute(String sql, Object... parameters) throws SQLException {
        try (Connection connection = connect()) {
            return execute(connection, sql, parameters);
        }
    }

    public static int execute(Connection connection, String sql, Object... parameters) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, parameters);
            return statement.executeUpdate();
        }
    }

    public static long insert(String sql, Object... parameters) throws SQLException {
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            bind(statement, parameters);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                return keys.next() ? keys.getLong(1) : 0;
            }
        }
    }

    public static Map<String, Object> one(String sql, Object... parameters) throws SQLException {
        try (Connection connection = connect()) {
            return one(connection, sql, parameters);
        }
    }

    public static Map<String, Object> one(Connection connection, String sql, Object... parameters) throws SQLException {
        List<Map<String, Object>> rows = query(connection, sql, parameters);
        return rows.isEmpty() ? null : rows.getFirst();
    }

    public static List<Map<String, Object>> query(String sql, Object... parameters) throws SQLException {
        try (Connection connection = connect()) {
            return query(connection, sql, parameters);
        }
    }

    public static List<Map<String, Object>> query(Connection connection, String sql, Object... parameters) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, parameters);
            try (ResultSet result = statement.executeQuery()) {
                return maps(result);
            }
        }
    }

    /** Intentionally unsafe query used only by S01. */
    public static Map<String, Object> unsafeOne(String sql) throws SQLException {
        try (Connection connection = connect(); Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(sql)) {
            List<Map<String, Object>> rows = maps(result);
            return rows.isEmpty() ? null : rows.getFirst();
        }
    }

    private static List<Map<String, Object>> maps(ResultSet result) throws SQLException {
        List<Map<String, Object>> rows = new ArrayList<>();
        ResultSetMetaData metadata = result.getMetaData();
        while (result.next()) {
            Map<String, Object> row = new LinkedHashMap<>();
            for (int index = 1; index <= metadata.getColumnCount(); index++) {
                Object value = result.getObject(index);
                if (value instanceof Clob clob) value = clob.getSubString(1, (int) clob.length());
                if (value instanceof Timestamp timestamp) value = timestamp.toLocalDateTime().toString();
                if (value instanceof java.sql.Date date) value = date.toLocalDate().toString();
                String label = metadata.getColumnLabel(index);
                if (label.equals(label.toUpperCase(Locale.ROOT))) label = label.toLowerCase(Locale.ROOT);
                row.put(label, value);
            }
            rows.add(row);
        }
        return rows;
    }

    private static void bind(PreparedStatement statement, Object... parameters) throws SQLException {
        for (int index = 0; index < parameters.length; index++) {
            statement.setObject(index + 1, parameters[index]);
        }
    }
